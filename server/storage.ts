export class NocStorage {
  private state: NocSystemState;
  private saveTimer: NodeJS.Timeout | null = null;

  constructor() {
    this.state = this.loadFromDisk();
  }

  private loadFromDisk(): NocSystemState {
    try {
      if (fs.existsSync(STATE_FILE)) {
        const raw = fs.readFileSync(STATE_FILE, 'utf-8');
        const parsed = JSON.parse(raw) as NocSystemState;
        if (parsed && Array.isArray(parsed.devices) && parsed.devices.length > 0) {
          if (!Array.isArray(parsed.dedicatedLine?.isps) || parsed.dedicatedLine.isps.length < 2) {
            const fresh = createInitialState();
            parsed.dedicatedLine = {
              ...fresh.dedicatedLine,
              ...parsed.dedicatedLine,
              activeIsp: parsed.dedicatedLine?.failoverActive
                ? 'isp-2'
                : parsed.dedicatedLine?.status === 'Offline'
                ? 'none'
                : 'isp-1',
              isps: fresh.dedicatedLine.isps,
            };
          }
          const isp2Link = parsed.links?.find((l) => l.id === 'lnk-isp2-fw');
          if (isp2Link && isp2Link.bandwidthMbps < 500) {
            isp2Link.bandwidthMbps = 500;
          }
          return parsed;
        }
      }
    } catch (err) {
      console.warn('Could not load saved NOC state, initializing fresh topology:', err);
    }
    const fresh = createInitialState();
    this.persistSync(fresh);
    return fresh;
  }

  public getState(): NocSystemState {
    return this.state;
  }

  public setState(next: NocSystemState): void {
    this.state = next;
    this.schedulePersist();
  }

  public resetState(): NocSystemState {
    this.state = createInitialState();
    this.persistSync(this.state);
    return this.state;
  }

  public schedulePersist(): void {
    if (this.saveTimer) return;
    this.saveTimer = setTimeout(() => {
      this.saveTimer = null;
      this.persistSync(this.state);
    }, 1000);
  }

  private persistSync(data: NocSystemState): void {
    try {
      if (!fs.existsSync(DATA_DIR)) {
        fs.mkdirSync(DATA_DIR, { recursive: true });
      }
      fs.writeFileSync(STATE_FILE, JSON.stringify(data, null, 2), 'utf-8');
    } catch (err) {
      console.error('Failed to persist NOC state:', err);
    }
  }
}
