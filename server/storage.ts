function makeHistory(baseCpu: number, baseMem: number, baseTraffic: number, baseLatency: number) {
  const points = [];
  const now = Date.now();
  for (let i = 11; i >= 0; i--) {
    const t = new Date(now - i * 5000);
    const jitter = ((i % 3) - 1) * 2.5;
    points.push({
      timestamp: t.toLocaleTimeString('en-US', { hour12: false }),
      cpuPct: Math.max(5, Math.min(98, Math.round(baseCpu + jitter))),
      memoryPct: Math.max(10, Math.min(95, Math.round(baseMem + jitter * 0.6))),
      trafficMbps: Math.max(1, Math.round((baseTraffic + jitter * 4) * 10) / 10),
      latencyMs: Math.max(1, Math.round((baseLatency + Math.abs(jitter) * 0.3) * 10) / 10),
    });
  }
  return points;
}

